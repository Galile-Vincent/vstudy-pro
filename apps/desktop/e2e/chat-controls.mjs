import { seedRoute } from './helpers/tab-route.mjs';
import { temporaryPath } from '../scripts/platform.mjs';
import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
const directory = await mkdtemp(join(tmpdir(),'vstudy-controls-'));
let app;
try {
 app = await electron.launch({args:[resolve('.'),`--user-data-dir=${directory}`],env:{...process.env,ELECTRON_RUN_AS_NODE:'',VSTUDY_FAKE_PROVIDER:'1'}});
 const page = await app.firstWindow();
 await page.evaluate(()=>window.sessionStorage.setItem('vstudy.memoryConsentPostponed','1'));
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1400,1000));
 await page.evaluate(()=>window.desktop.invoke('settings:set',{onboardingCompleted:true,welcomeSeen:true}));
 await seedRoute(page,{view:'workspace'}); await page.reload(); const errors=[]; page.on('pageerror',e=>{errors.push(e.message); console.log('PAGEERROR',e.message);}); page.on('console', m=>{if(m.type()==='error') {errors.push(`console: ${m.text()}`);console.log('CONSOLE',m.text());}});
 await page.getByTestId('bridge-status').waitFor({state:'attached'});
 await app.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},resolve('e2e/fixtures/reading.md'));
 await page.getByTestId('import-document').click();
 await page.getByTestId('document-markdown').waitFor();
 await page.locator('.aui-composer-input').waitFor();
 const input=page.locator('.aui-composer-input'); await input.waitFor();
 await input.fill('Unsent tab draft');
 const modifier=process.platform==='darwin'?'Meta':'Control';
 await page.keyboard.press(`${modifier}+t`);
 await page.locator('.app-tabs-menu').getByRole('button',{name:'Home',exact:true}).click();
 await page.keyboard.press(`${modifier}+1`);
 await input.waitFor();assert.equal(await input.inputValue(),'Unsent tab draft');
 await input.fill('');
 await page.getByRole('combobox',{name:'Model',exact:true}).click();
 await page.screenshot({path: temporaryPath('vstudy-picker-open.png'), animations:'disabled'});
 await page.getByRole('combobox',{name:'Search models'}).fill('Fake');
 await page.screenshot({path: temporaryPath('vstudy-picker-search.png'), animations:'disabled'});
 await page.locator('[data-slot=model-selector-list] [role=option]').filter({hasText:'Fake'}).click();
 await page.getByRole('combobox',{name:'Effort',exact:true}).click();
 await page.getByRole('option',{name:'High',exact:true}).click();
 assert.match(await page.getByRole('combobox',{name:'Effort',exact:true}).innerText(),/High/);
 assert.equal(await page.getByRole('button',{name:'Stop generating',exact:true}).count(),0);
 await input.fill('Explain');
 await page.screenshot({path: temporaryPath('vstudy-composer-effort.png'), animations:'disabled'});
 await input.dispatchEvent('compositionstart'); await input.press('Enter');
 assert.equal(await page.locator('[data-role=user]').count(),0,'IME Enter must not send');
 await input.dispatchEvent('compositionend'); await input.press('Enter');
 await page.getByRole('button',{name:'Stop generating',exact:true}).waitFor();
 await page.screenshot({path: temporaryPath('vstudy-loading.png'), animations:'disabled'});
 await page.waitForFunction(()=>!window.document.querySelector('.aui-composer-cancel'));
 const conversation = await page.evaluate(async()=>{const d=await window.desktop.invoke('documents:list',{});return (await window.desktop.invoke('conversations:list',{documentId:d[0].id}))[0];});
 assert.deepEqual(conversation.options,{effort:'high'});
 const before = await page.evaluate(id=>window.desktop.invoke('messages:list',{conversationId:id}),conversation.id);
 assert.deepEqual(before[0].parts[0].options,{effort:'high'});
 assert.match(await page.locator('[data-role=assistant] .usage-chip').first().innerText(),/High/);
 await page.bringToFront();
 await page.locator('.aui-assistant-action-bar-root').getByRole('button',{name:'Copy',exact:true}).click();
 await page.locator('.aui-assistant-action-bar-root svg.lucide-check').waitFor();
 assert.match(await app.evaluate(({clipboard})=>clipboard.readText()),/bold/);
 await page.locator('[data-role=assistant]').getByRole('button',{name:'Regenerate',exact:true}).click();
 await page.waitForFunction(()=>!window.document.querySelector('.aui-composer-cancel'));
 const usage = await page.evaluate(id=>window.desktop.invoke('usage:forConversation',{conversationId:id}),conversation.id);
 assert.equal(usage.length,2,'regeneration is a separately recorded real call');
 await page.locator('[data-role=user]').hover();
 await page.locator('[data-role=user]').getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByRole('textbox',{name:'Edit message',exact:true}).fill('Edited question');
 await page.getByRole('button',{name:'Save & resend',exact:true}).click();
 await page.waitForFunction(()=>!window.document.querySelector('.aui-composer-cancel'));
 const edited=await page.evaluate(id=>window.desktop.invoke('messages:list',{conversationId:id}),conversation.id);
 assert.equal(edited.filter(m=>m.role==='user').at(-1).parts[0].text,'Edited question');
 await input.fill('test error'); await input.press('Enter');
 const error=page.locator('.aui-message-error-root'); await error.getByRole('button',{name:'Retry',exact:true}).waitFor();
 assert.match(await error.innerText(),/rate limit/i);
 assert.equal(await page.locator('.aui-thread-followup-suggestions').count(),0);
 await page.locator('[data-slot=aui_thread-viewport]').evaluate(el=>el.scrollTo({top:el.scrollHeight,behavior:'instant'}));
 await page.screenshot({path: temporaryPath('vstudy-error-retry.png'), animations:'disabled'});
 await page.reload();
 await error.getByRole('button',{name:'Retry',exact:true}).last().waitFor();
 assert.match(await error.last().innerText(),/rate limit/i);
 await error.getByRole('button',{name:'Retry',exact:true}).last().click();
 await page.waitForFunction(()=>!window.document.querySelector('.aui-composer-cancel'));
 await page.emulateMedia({colorScheme:'dark'});
 await page.getByRole('combobox',{name:'Model',exact:true}).click();
 await page.screenshot({path: temporaryPath('vstudy-picker-dark.png'), animations:'disabled'});
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('tab',{name:'Usage',exact:true}).click();
 assert.equal(await page.getByRole('tab',{name:'Usage',exact:true}).getAttribute('aria-selected'),'true');
 await page.getByRole('button',{name:'Close settings'}).click();
 assert.deepEqual(errors,[]); console.log('PASS chat controls: IME, options, copy, regenerate usage, error/retry, dark mode');
} catch(error) { if(app) { const p=await app.firstWindow(); console.log(await p.locator('body').innerText()); await p.screenshot({path:temporaryPath('vstudy-controls-failure.png')}); } throw error; } finally { await app?.close(); await rm(directory,{recursive:true,force:true}); }
