import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
const directory = await mkdtemp(join(tmpdir(),'vstudy-controls-'));
let app;
try {
 app = await electron.launch({args:[resolve('.'),`--user-data-dir=${directory}`],env:{...process.env,ELECTRON_RUN_AS_NODE:'',VSTUDY_FAKE_PROVIDER:'1'}});
 const page = await app.firstWindow(); const errors=[]; page.on('pageerror',e=>{errors.push(e.message); console.log('PAGEERROR',e.message);}); page.on('console', m=>{if(m.type()==='error') console.log('CONSOLE',m.text());});
 await page.getByRole('heading',{name:'VStudy Pro'}).waitFor();
 await app.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},resolve('e2e/fixtures/reading.md'));
 await page.getByRole('button',{name:'＋ Import document',exact:true}).click();
 await page.getByTestId('document-markdown').waitFor();
 await page.getByRole('button',{name:'Model',exact:true}).click();
 await page.locator('#model-list [role=option]').filter({hasText:'Fake'}).click();
 await page.getByRole('button',{name:'Start a conversation',exact:true}).click();
 const input=page.getByRole('textbox',{name:'Ask about your document',exact:true}); await input.waitFor();
 await page.getByRole('button',{name:'Model',exact:true}).click();
 await page.screenshot({path:'/tmp/vstudy-picker-open.png'});
 await page.getByRole('combobox',{name:'Search models'}).fill('Fake');
 await page.screenshot({path:'/tmp/vstudy-picker-search.png'});
 await page.locator('#model-list [role=option]').filter({hasText:'Fake'}).click();
 await page.getByRole('radio',{name:'high',exact:true}).click();
 await input.fill('Explain');
 await page.screenshot({path:'/tmp/vstudy-composer-effort.png'});
 await input.dispatchEvent('compositionstart'); await input.press('Enter');
 assert.equal(await page.locator('.message.user').count(),0,'IME Enter must not send');
 await input.dispatchEvent('compositionend'); await input.press('Enter');
 await page.getByRole('status').filter({hasText:'Thinking'}).waitFor();
 await page.screenshot({path:'/tmp/vstudy-loading.png'});
 await page.waitForFunction(()=>window.document.querySelector('.stop-button')?.disabled===true);
 const conversation = await page.evaluate(async()=>{const d=await window.desktop.invoke('documents:list',{});return (await window.desktop.invoke('conversations:list',{documentId:d[0].id}))[0];});
 assert.deepEqual(conversation.options,{effort:'high'});
 const before = await page.evaluate(id=>window.desktop.invoke('messages:list',{conversationId:id}),conversation.id);
 assert.deepEqual(before[0].parts[0].options,{effort:'high'});
 await page.bringToFront();
 await page.locator('.message.assistant').getByRole('button',{name:'Copy',exact:true}).click();
 await page.getByRole('button',{name:'Copied',exact:true}).waitFor();
 assert.match(await app.evaluate(({clipboard})=>clipboard.readText()),/bold/);
 await page.locator('.message.assistant').getByRole('button',{name:'Regenerate',exact:true}).click();
 await page.waitForFunction(()=>window.document.querySelector('.stop-button')?.disabled===true);
 const usage = await page.evaluate(id=>window.desktop.invoke('usage:forConversation',{conversationId:id}),conversation.id);
 assert.equal(usage.length,2,'regeneration is a separately recorded real call');
 await page.locator('.message.user').getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByRole('textbox',{name:'Edit message',exact:true}).fill('Edited question');
 await page.getByRole('button',{name:'Save & resend',exact:true}).click();
 await page.waitForFunction(()=>window.document.querySelector('.stop-button')?.disabled===true);
 const edited=await page.evaluate(id=>window.desktop.invoke('messages:list',{conversationId:id}),conversation.id);
 assert.equal(edited.filter(m=>m.role==='user').at(-1).parts[0].text,'Edited question');
 await input.fill('test error'); await input.press('Enter');
 const error=page.locator('.chat-error'); await error.getByRole('button',{name:'Retry',exact:true}).waitFor();
 assert.match(await error.innerText(),/rate limited/i);
 await page.screenshot({path:'/tmp/vstudy-error-retry.png'});
 await page.reload();
 await error.getByRole('button',{name:'Retry',exact:true}).last().waitFor();
 assert.match(await error.last().innerText(),/rate limited/i);
 await error.getByRole('button',{name:'Retry',exact:true}).last().click();
 await page.waitForFunction(()=>window.document.querySelector('.stop-button')?.disabled===true);
 await page.emulateMedia({colorScheme:'dark'});
 await page.getByRole('button',{name:'Model',exact:true}).click();
 await page.screenshot({path:'/tmp/vstudy-picker-dark.png'});
 assert.deepEqual(errors,[]); console.log('PASS chat controls: IME, options, copy, regenerate usage, error/retry, dark mode');
} catch(error) { if(app) { const p=await app.firstWindow(); console.log(await p.locator('body').innerText()); await p.screenshot({path:'/tmp/vstudy-controls-failure.png'}); } throw error; } finally { await app?.close(); await rm(directory,{recursive:true,force:true}); }
