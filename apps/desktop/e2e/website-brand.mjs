/** Production website regressions for session, replay, reduced motion, hidden tabs, and brand accessibility. */
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const origin=process.env.BRAND_SITE ?? 'http://127.0.0.1:4382/vstudy-pro/';
const evidence=resolve('../../docs/evidence/brand/website');
const browser=await chromium.launch({headless:true,channel:process.env.BRAND_BROWSER_CHANNEL ?? 'chrome'});
const results=[];
try {
  await mkdir(evidence,{recursive:true});
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(origin+'en/');
  await page.waitForTimeout(500);
  assert.equal(await page.locator('.butterfly-flight').isHidden(),true);
  assert.equal(await page.evaluate(()=>window.sessionStorage.getItem('vstudy-butterflies-v1')),null);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.reload();
  await page.waitForFunction(()=>!window.document.querySelector('.butterfly-flight').hidden);
  assert.equal(await page.locator('.butterfly:not([hidden])').count(),4);
  await page.waitForFunction(()=>window.document.querySelector('.butterfly-flight').hidden,undefined,{timeout:10000});
  await page.reload();await page.waitForTimeout(500);
  assert.equal(await page.locator('.butterfly-flight').isHidden(),true);
  await page.evaluate(()=>window.scrollTo(0,500));
  await page.locator('.site-header .brand').click();
  await page.waitForFunction(()=>window.scrollY===0&&!window.document.querySelector('.butterfly-flight').hidden);
  assert.equal(await page.locator('.butterfly-flight').isHidden(),false);
  await page.waitForTimeout(500);
  await page.evaluate(()=>{Object.defineProperty(window.document,'hidden',{configurable:true,get:()=>true});window.document.dispatchEvent(new window.Event('visibilitychange'));});
  const paused=await page.locator('.butterfly').first().getAttribute('style');
  await page.waitForTimeout(400);
  assert.equal(await page.locator('.butterfly').first().getAttribute('style'),paused);
  await page.evaluate(()=>{delete window.document.hidden;window.document.dispatchEvent(new window.Event('visibilitychange'));});
  await page.waitForTimeout(200);
  assert.notEqual(await page.locator('.butterfly').first().getAttribute('style'),paused);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.butterfly-flight').isHidden(),true);
  for(const language of ['en','zh-Hant','ja'])for(const scheme of ['light','dark'])for(const width of [390,1440]) {
    await page.setViewportSize({width,height:900});
    await page.goto(origin+language+'/');
    if(await page.locator('html').getAttribute('data-scheme')!==scheme) await page.locator('#scheme-toggle').click();
    assert.equal(await page.evaluate(()=>window.document.documentElement.scrollWidth>window.innerWidth),false);
    const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
    results.push({language,scheme,width,violations:audit.violations.map(v=>v.id)});
    assert.deepEqual(audit.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
    if(width===390)await page.screenshot({path:resolve(evidence,`${language}-${scheme}-${width}-verified.png`)});
  }
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto(origin+'en/');await page.locator('.hero-brand').click();
  assert.equal(await page.locator('.butterfly:not([hidden])').count(),4);
  await page.setViewportSize({width:390,height:844});await page.locator('.hero-brand').click();
  assert.equal(await page.locator('.butterfly:not([hidden])').count(),3);
  await page.goto(origin+'en/docs/getting-started/');
  assert.equal(await page.locator('.butterfly-flight').count(),0);
  const hiddenPage=await context.newPage();
  await hiddenPage.addInitScript(()=>Object.defineProperty(window.document,'hidden',{configurable:true,get:()=>true}));
  await hiddenPage.goto(origin+'en/');await hiddenPage.waitForTimeout(400);
  assert.equal(await hiddenPage.locator('.butterfly-flight').isHidden(),true);
  await hiddenPage.evaluate(()=>{Object.defineProperty(window.document,'hidden',{configurable:true,get:()=>false});window.document.dispatchEvent(new window.Event('visibilitychange'));});
  await hiddenPage.waitForFunction(()=>!window.document.querySelector('.butterfly-flight').hidden);
  await hiddenPage.close();
  assert.deepEqual(errors,[]);
  await writeFile(resolve(evidence,'behavior-results.json'),JSON.stringify({errors,session:true,replay:true,reducedMotion:true,hiddenTabPause:true,initiallyHiddenTabArrival:true,scrolledLogoReplay:true,mobileCount:3,desktopCount:4,docsHaveNoFlight:true,audits:results},null,2)+'\n');
  console.log('PASS. Session, replay, reduced motion, hidden-tab pause, desktop/mobile counts, docs exclusion, and twelve WCAG audits.');
} finally {await browser.close();}
