import { _electron as electron } from "playwright";
import assert from "node:assert/strict";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
const directory = await mkdtemp(join(tmpdir(), "vstudy-visual-"));
const fixture = join(directory, "preview.md");
await writeFile(fixture, `# ${"Long heading path ".repeat(20)}\n\n**Blue** [fern](https://example.com) ![image](image.png)\n\n- First\n- Second\n\n${"More reading. ".repeat(30)}`);
let app, page;
const errors = [];
const launch = async () => {
  app = await electron.launch({ args: [resolve("."), `--user-data-dir=${join(directory, "user-data")}`], env: { ...process.env, ELECTRON_RUN_AS_NODE: "", VSTUDY_LOCALE:"en", VSTUDY_FAKE_PROVIDER: "1" } });
  page = await app.firstWindow();
 await page.evaluate(()=>window.localStorage.setItem('vstudy-route',JSON.stringify({view:'workspace'}))); await page.reload();
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", msg => { if (/Content Security Policy|Refused to (?:apply|load|execute)/i.test(msg.text())) errors.push(msg.text()); });
  await page.getByTestId("bridge-status").waitFor({state:"attached"});
};
try {
  await launch();
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, fixture);
  await page.getByTestId("import-document").click();
  const viewer = page.getByTestId("document-markdown");
  await viewer.waitFor();
  assert.equal(await viewer.locator('h1').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'long document headings wrap within the reader');
  await viewer.locator("h1").hover();
  await viewer.locator(".section-action").focus();
  await viewer.locator(".section-action").press("Enter");
  const input = page.locator('.aui-composer-input');
  await input.waitFor();
  const chip = page.locator(".aui-composer-root .selection-preview");
  assert.ok(!(await chip.innerText()).includes("**Blue**"));
  assert.ok(!(await chip.innerText()).includes("image.png"));
  assert.equal(await chip.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true);
  assert.equal((await chip.locator("summary span").innerText()).length, 161);
  await page.screenshot({path: "/tmp/vstudy-visual-section.png", animations:'disabled'});
  await chip.locator("summary").click();
  assert.ok((await chip.innerText()).includes("Blue fern"));
  await input.fill("Explain");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await page.locator("[data-role=assistant] strong").waitFor();
  await page.waitForFunction(() => !window.document.querySelector(".aui-composer-cancel"));
  assert.equal(await page.locator("[data-role=assistant] strong").innerText(), "bold");
  assert.deepEqual(await page.locator("[data-role=assistant] li").allTextContents(), ["First", "Second"]);
  await page.locator("[data-role=assistant] strong").scrollIntoViewIfNeeded();
  await page.screenshot({path: "/tmp/vstudy-visual-markdown.png", animations:'disabled'});
  for (const name of ["Delete document"]) {
    const button = page.getByRole("button", { name, exact: true });
    assert.equal(Math.round((await button.boundingBox()).width), 28);
    assert.equal(await button.getAttribute("class"), "icon-button");
  }
  await input.fill("Preserved draft");
  await page.getByRole("combobox", { name: "Model", exact: true }).click();
  await page.getByRole("combobox", { name: "Search models" }).fill("fixture");
  await page.getByRole("option").filter({hasText:"Fixture model (test only)"}).first().click();
  await page.waitForFunction(() => window.document.querySelector('.model-trigger')?.textContent.includes("Fixture model"));
  assert.equal(await input.inputValue(), "Preserved draft");
  await app.close();
  await launch();
  await page.locator('.aui-composer-input').waitFor();
  await page.getByRole("combobox", { name: "Model", exact: true }).filter({ hasText: "Fixture model (test only)" }).waitFor();
  assert.equal(await page.evaluate(() => window.desktop.invoke("settings:get", {}).then(s => `${s.lastProviderId}/${s.lastModelId}`)), "anthropic-api/fixture-model");
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: "PASS", screenshots: ["/tmp/vstudy-visual-section.png", "/tmp/vstudy-visual-markdown.png"], consoleErrors: errors }));
} finally { await app?.close(); await rm(directory, { recursive: true, force: true }); }
