import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const evidence = resolve('../../docs/evidence/app-tabs');
await mkdir(evidence, { recursive: true });
const profile = await mkdtemp(join(tmpdir(), 'vstudy-app-tabs-'));
const env = { ...process.env, ELECTRON_RUN_AS_NODE: '', VSTUDY_FAKE_PROVIDER: '1', VSTUDY_LOCALE: 'en' };
delete env.ELECTRON_RENDERER_URL;
const modifier = process.platform === 'darwin' ? 'Meta' : 'Control';
let app;
const results = [];
const launch = () => electron.launch({ args: [resolve('.'), `--user-data-dir=${profile}`], env });
try {
  app = await launch();
  let page = await app.firstWindow();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.evaluate(async () => {
    const settings = await window.desktop.invoke('settings:get', {});
    await window.desktop.invoke('settings:set', { ...settings, onboardingCompleted: true, welcomeSeen: true, language: 'en' });
    await window.desktop.invoke('analytics:setConsent', {enabled:false});
    localStorage.setItem('vstudy-onboarding-v1', JSON.stringify({ version: 1, status: 'completed', done: ['setup'], dismissed: ['home', 'library', 'courses'] }));
  });
  await page.reload();
  await page.locator('.app-shell[data-view=home]').waitFor();
  await page.keyboard.press(`${modifier}+t`);
  await page.locator('.app-tabs-menu').getByRole('button', { name: 'Library', exact: true }).click();
  await page.getByRole('tab', { name: 'Library', exact: true }).waitFor();
  await page.evaluate(async () => { await window.desktop.invoke('documents:importSample', { language: 'en' }); window.dispatchEvent(new Event('library-changed')); });
  const title = page.locator('.library-document .document-title').first();
  await page.locator('.course-folder').first().click();
  await title.waitFor({timeout:5000});
  await title.click({ modifiers: [modifier] });
  await page.locator('.app-shell[data-view=workspace]').waitFor();
  assert.equal(await page.getByRole('tab').count(), 3);
  assert.equal(await page.getByRole('tablist').isVisible(), true);
  await page.screenshot({path:join(evidence,'workspace-tabs.png')});
  assert.equal(await page.getByRole('tabpanel').count(), 1);
  assert.equal(await page.locator('.workspace').count(), 1);
  assert.equal(await page.locator('.home-page,.library-view').count(), 0);
  await page.getByRole('tab', { name: 'Home', exact: true }).click();
  await page.locator('.app-shell[data-view=home]').waitFor();
  await page.keyboard.press('Meta+Shift+BracketRight');
  await page.locator('.app-shell[data-view=library]').waitFor();
  await page.keyboard.press(`${modifier}+1`);
  await page.locator('.app-shell[data-view=home]').waitFor();
  results.push('PASS three tabs, workspace strip visible, click and keyboard switching, one panel');
  await page.getByRole('tab', { name: 'Library', exact: true }).click({ button: 'middle' });
  assert.equal(await page.getByRole('tab').count(), 2);
  await page.keyboard.press(`${modifier}+w`);
  await page.locator('.app-shell[data-view=workspace]').waitFor();
  results.push('PASS middle click and Cmd/Ctrl+W close with neighbor selection');
  await page.keyboard.press(`${modifier}+t`);
  await page.locator('.app-tabs-menu').getByRole('button', { name: 'Home', exact: true }).click();
  await page.keyboard.press(`${modifier}+t`);
  await page.locator('.app-tabs-menu').getByRole('button', { name: 'Library', exact: true }).click();
  const library = page.getByRole('tab', { name: 'Library', exact: true });
  await library.focus();
  await page.keyboard.press('Shift+ArrowLeft');
  await page.waitForFunction(() => document.querySelectorAll('[role=tab]')[1]?.textContent === 'Library');
  const beforeDrag = await page.getByRole('tab').evaluateAll(tabs => tabs.map(tab => tab.id));
  const first = await page.getByRole('tab').first().boundingBox();
  const last = await page.getByRole('tab').last().boundingBox();
  await page.mouse.move(first.x + 30, first.y + 15); await page.mouse.down();
  await page.mouse.move(last.x + 30, last.y + 15, { steps: 10 }); await page.mouse.up();
  await page.waitForFunction(expected => Array.from(document.querySelectorAll('[role=tab]')).map(tab=>tab.id).join() === expected.join(), [...beforeDrag.slice(1),beforeDrag[0]]);
  await page.waitForTimeout(300);
  await page.screenshot({ path: join(evidence, 'tabs-reordered.png') });
  const snapshot = await page.evaluate(() => JSON.parse(localStorage.getItem('vstudy-tabs-v1')));
  await app.close(); app = await launch(); page = await app.firstWindow();
  await page.getByRole('tab').nth(2).waitFor();
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('vstudy-tabs-v1')));
  assert.deepEqual(restored.tabs.map(tab => tab.id), snapshot.tabs.map(tab => tab.id));
  assert.equal(restored.activeId, snapshot.activeId);
  assert.equal(await page.locator('[data-tab-id]').count(), 1);
  assert.equal(await page.locator('.home-page,.library-view,.workspace').count(), 1);
  assert.equal(await page.locator('[data-tab-id]').getAttribute('data-tab-id'), snapshot.activeId);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: join(evidence, 'tabs-restored.png') });
  results.push('PASS keyboard and pointer reorder, restart restores order and active tab, only active view mounted');
} catch (error) { const page = await app?.firstWindow(); if(page) {await page.screenshot({path:join(evidence,'failure.png')}); await writeFile(join(evidence,'failure.txt'),await page.locator('body').ariaSnapshot());} results.push(`FAIL ${error.stack}`); process.exitCode = 1; }
finally {
  await app?.close(); await rm(profile, { recursive: true, force: true });
  await writeFile(join(evidence, 'results.json'), JSON.stringify(results, null, 2));
  console.log(results.join('\n'));
}
